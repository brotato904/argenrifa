// COMPARTIR POR WHATSAPP
// =========================

function compartirPorWhatsApp(id) {

    const rifa = rifas.find(function (r) {
        return r.id === id;
    });

    if (!rifa) return;


    const disponibles =
        rifa.cantidad - rifa.numerosOcupados.length;


    // Mensaje prearmado
    const mensaje =
        "🎟️ ¡Mirá esta rifa!\n\n" +
        "🎁 *" + rifa.titulo + "*\n" +
        "📝 " + rifa.descripcion + "\n" +
        "💰 Precio por número: $" + rifa.precio + "\n" +
        "🎟️ Números disponibles: " + disponibles + "\n" +
        "📍 " + rifa.provincia + ", " + rifa.pais + "\n\n" +
        "👉 Participá acá: " + window.location.href;


    // Codificar el mensaje para la URL
    const mensajeCodificado =
        encodeURIComponent(mensaje);


    // Detectar si es celular o PC
    const esCelular =
        /Android|iPhone|iPad|iPod|Mobile/i.test(navigator.userAgent);


    let url;

    if (esCelular) {
        // En celular: abrir la app de WhatsApp
        url = "whatsapp://send?text=" + mensajeCodificado;
    } else {
        // En PC: abrir WhatsApp Web
        url = "https://web.whatsapp.com/send?text=" + mensajeCodificado;
    }


    window.open(url, "_blank");

}

