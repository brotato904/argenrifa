function alternarEstado(id) {

    const rifa = rifas.find(function (r) {
        return r.id === id;
    });

    if (!rifa) return;

    // Si no tiene estado, lo inicializamos
    if (!rifa.estado) {
        rifa.estado = "activa";
    }

    if (rifa.estado === "activa") {
        rifa.estado = "desactivada";
    } else if (rifa.estado === "desactivada") {
        rifa.estado = "activa";
    }

    guardarRifas();
    mostrarRifas();

}


function cerrarConGanador(id) {

    const rifa = rifas.find(function (r) {
        return r.id === id;
    });

    if (!rifa) return;

    if (rifa.numerosOcupados.length === 0) {
        alert("⚠️ Todavía no hay números vendidos. No se puede elegir un ganador.");
        return;
    }

    const confirmar = confirm(
        "¿Sortear un ganador entre los números vendidos?\n\n" +
        "Esta acción cerrará la rifa y no se podrá reabrir."
    );

    if (!confirmar) return;

    const indiceAleatorio = Math.floor(
        Math.random() * rifa.numerosOcupados.length
    );

    const numeroGanador = rifa.numerosOcupados[indiceAleatorio];

    let usuarioGanador = "Desconocido";

    rifa.participantes.forEach(function (participante) {
        if (participante.numeros.includes(numeroGanador)) {
            usuarioGanador = participante.usuario;
        }
    });

    rifa.ganador = numeroGanador;
    rifa.usuarioGanador = usuarioGanador;
    rifa.estado = "cerrada";

    guardarRifas();
    mostrarRifas();

    alert(
        "🎉 ¡Ganador elegido!\n\n" +
        "Número: " + numeroGanador + "\n" +
        "Usuario: " + usuarioGanador
    );

}


async function borrarRifa(id) {

    const rifa = rifas.find(function (r) {
        return r.id === id;
    });

    if (!rifa) return;

    const confirmar = confirm(
        "¿Seguro que quieres borrar la rifa \"" +
        rifa.titulo + "\"?\n\n" +
        "Esta acción no se puede deshacer."
    );

    if (!confirmar) return;


    // Borrar de la base de datos D1
    try {

        await fetch("/api/rifas?id=" + id, {
            method: "DELETE"
        });

    } catch (error) {

        console.error("Error al borrar:", error);

    }


    // Borrar de la lista local
    rifas = rifas.filter(function (r) {
        return r.id !== id;
    });

    mostrarRifas();

}


