function abrirEditarRifa(id) {

    const rifa =
        rifas.find(function (r) {
            return r.id === id;
        });

    if (!rifa) return;

    if (rifa.creador !== usuarioActual) {
        alert("⚠️ Solo el creador puede editar esta rifa.");
        return;
    }

    rifaEditandoId = id;

    // Cargar datos en el panel
    editarTitulo.value = rifa.titulo;
    editarDescripcion.value = rifa.descripcion;
    editarPrecio.value = rifa.precio;

    editarImagenBase64.value = rifa.imagen || "";

    if (rifa.imagen) {
        previewEditarImagen.innerHTML =
            "<img src='" + rifa.imagen + "'>";
        botonQuitarImagenEditar.style.display = "inline-block";
    } else {
        previewEditarImagen.innerHTML = "";
        botonQuitarImagenEditar.style.display = "none";
    }

    // Mostrar panel
    overlayEditar.classList.add("activo");
    panelEditar.classList.add("activo");

}


